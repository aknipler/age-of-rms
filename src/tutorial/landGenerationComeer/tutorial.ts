/**
 * Wide enough for any number the tutorial hides. Every number spoiler is
 * masked as this, so a bar of one digit width never rules out a two digit
 * answer.
 */
const NUMBER_MASK = "0000";

function numberSpoiler(value: number): Inline {
  return { spoiler: String(value), maskAs: NUMBER_MASK };
}

/**
 * "A value between 10 and 40 should work. We pick 20." with all three numbers
 * hidden. The learner opens whichever they want, so a learner who has found
 * their own range can check just the pick.
 */
function rangeSentence(
  range: { min: number; max: number },
  pick: number,
  subject = "A value",
): Inline[] {
  return [
    `${subject} between `,
    numberSpoiler(range.min),
    " and ",
    numberSpoiler(range.max),
    " should work. We pick ",
    numberSpoiler(pick),
    ".",
  ];
}

/**
 * The maths behind "Player land growth"'s prediction answer, built from the
 * same helpers the generator's behaviour is described by, so the numbers in
 * the dropdown cannot drift from the constants the rest of the tutorial uses.
 * Tests pin that `NO_GROWTH_PERCENT` stays under the starting square and the
 * next value goes over it.
 */
const NO_GROWTH_PERCENT = largestPercentWithoutGrowth(OVERSIZED_BASE_SIZE);

function growthExplanation(): string {
  const square = startingSquareTiles(OVERSIZED_BASE_SIZE);
  const side = 2 * OVERSIZED_BASE_SIZE + 1;
  const tiles = TINY_MAP_WIDTH ** 2;
  const line = (percent: number): string => {
    const target = playerIslandTarget(percent);
    return target <= square
      ? `At land_percent ${percent}, each island aims for ${target}, which is less than the starting size due to base_size, so nothing grows.`
      : `At land_percent ${percent}, each island aims for ${target}, so ${target - square} tiles grow.`;
  };
  return `The starting square counts toward land_percent. At base_size ${OVERSIZED_BASE_SIZE} it is ${side} x ${side} = ${square} tiles. The Tiny map has ${tiles} tiles and the two players share land_percent, so each island aims for ${tiles} x (land_percent / 100) / 2 tiles. ${line(NO_GROWTH_PERCENT)} ${line(NO_GROWTH_PERCENT + 1)} ${line(20)}`;
}

