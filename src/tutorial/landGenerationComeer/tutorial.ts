function numeric(text: string | undefined): number | null {
  if (text === undefined || !/^-?\d+(\.\d+)?$/.test(text)) return null;
  return Number(text);
}

function inRange(
  text: string | undefined,
  range: { min: number; max: number },
): boolean {
  const n = numeric(text);
  return n !== null && n >= range.min && n <= range.max;
}

/** True when some `create_player_lands` has every border attribute passing `test`. */
function playerBorders(
  ctx: StepContext,
  test: (args: string[]) => boolean,
): boolean {
  return commandAttributeMaps(ctx.parseResult, LAND, PLAYER_LANDS).some((m) =>
    BORDER_ATTRIBUTES.every((name) => {
      const args = m.get(name);
      return args !== undefined && test(args);
    }),
  );
}

function playerAttribute(
  ctx: StepContext,
  attribute: string,
  test: (args: string[]) => boolean,
): boolean {
  return commandAttributeMaps(ctx.parseResult, LAND, PLAYER_LANDS).some((m) => {
    const args = m.get(attribute);
    return args !== undefined && test(args);
  });
}

/**
 * True when `zone` would put a neutral land in the same zone as the player
 * lands. A `zone` written on create_player_lands wins, and without one the
 * engine gives each player a zone of their own in -9 to -2, so a neutral land
 * with no zone, or one inside that span, is a player's zone.
 */
function isPlayerZone(ctx: StepContext, zone: string | undefined): boolean {
  const n = numeric(zone);
  if (n === null) return true;
  const written = commandAttributeMaps(ctx.parseResult, LAND, PLAYER_LANDS)
    .map((m) => numeric(m.get("zone")?.[0]))
    .filter((z): z is number => z !== null);
  if (written.length > 0) return written.includes(n);
  return n >= -9 && n <= -2;
}

function neutralLands(ctx: StepContext): Map<string, string[]>[] {
  return commandAttributeMaps(ctx.parseResult, LAND, CREATE_LAND);
}

type Edge = "near" | "far";

/** Which edge of the map a `land_position` number sits at, or null for neither (100 is neither). */
function edgeOf(text: string | undefined): Edge | null {
  if (inRange(text, RANGES.cornerNear)) return "near";
  if (inRange(text, RANGES.cornerFar)) return "far";
  return null;
}

/** The map is drawn as a diamond, so the 0 0 corner is its left point. */
const LEFT_CORNER = "near near";

/** The corner a land is in, as "near far" and so on, or null when either number is off the edges. */
function cornerOf(land: Map<string, string[]>): string | null {
  const position = land.get("land_position");
  if (position === undefined || position.length !== 2) return null;
  const x = edgeOf(position[0]);
  const y = edgeOf(position[1]);
  return x === null || y === null ? null : `${x} ${y}`;
}

/** A neutral land attribute that is a number inside `range`, or `rnd(a,b)` with both ends inside it. */
function inRangeOrRnd(
  args: string[] | undefined,
  range: { min: number; max: number },
): boolean {
  if (args === undefined || args.length !== 1) return false;
  if (inRange(args[0], range)) return true;
  const match = /^rnd\((-?\d+),(-?\d+)\)$/.exec(args[0]);
  return (
    match !== null &&
    Number(match[1]) <= Number(match[2]) &&
    inRange(match[1], range) &&
    inRange(match[2], range)
  );
}

function hasRndInRange(
  args: string[] | undefined,
  range: { min: number; max: number },
): boolean {
  if (args === undefined || args.length !== 1) return false;
  return /^rnd\(/.test(args[0]) && inRangeOrRnd(args, range);
}

