"""Build the Age of RMS logo as outlined SVG paths.

Layout is the middle option of the second logo round, "Text only, one word per
line": A G E and R M S spread to the same width, OF between two gold rules.
Letters are converted to paths so the SVG renders the same without Cinzel
installed. Cinzel is SIL OFL 1.1, which allows this.

Writes public/logo/age-of-rms-logo-light.svg, public/logo/age-of-rms-logo-dark.svg
and src/components/logoPaths.ts (the same geometry for the themed React logo).

Run `python tools/logo/build_logo.py` from age-of-rms/ after `npm install`.
Needs fontTools (`pip install fonttools`).
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "node_modules" / "@fontsource" / "cinzel" / "files"

BIG_PX = 110  # size of AGE and RMS, as in the draft
OF_PX = 44  # size of OF
WIDTH = 330  # advance width the three letters of a line are spread across
RULE_GAP = 14  # space between a rule and OF
RULE_THICK = 3
ROW_GAP = 20  # space between a big line's baseline and the OF row's cap top
PAD = 6

COLOURS = {
    "light": {"ink": "#1d2736", "gold": "#c28f1f"},
    "dark": {"ink": "#eef2f9", "gold": "#e0ae3c"},
}


def load(weight):
    return TTFont(FONTS / f"cinzel-latin-{weight}-normal.woff")


def glyph_path(font, ch, size, x, baseline):
    """SVG path data for one character, scaled to `size` px and placed with
    its origin at (x, baseline). SVG's y axis points down, so y is flipped."""
    scale = size / font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[ord(ch)]
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
    return pen.getCommands(), glyphs[name].width * scale


def cap_height(font, size):
    return font["OS/2"].sCapHeight * size / font["head"].unitsPerEm


def spread(font, text, size, baseline, left):
    """Letters of `text` spread edge to edge across WIDTH, like CSS
    `justify-content: space-between` on their advance boxes."""
    advances = [glyph_path(font, ch, size, 0, 0)[1] for ch in text]
    gap = (WIDTH - sum(advances)) / (len(text) - 1)
    paths, x = [], left
    for ch, adv in zip(text, advances):
        paths.append(glyph_path(font, ch, size, x, baseline)[0])
        x += adv + gap
    return paths


def build():
    bold, semi = load(700), load(600)
    big_cap = cap_height(bold, BIG_PX)
    of_cap = cap_height(semi, OF_PX)

    base1 = PAD + big_cap
    of_top = base1 + ROW_GAP
    of_base = of_top + of_cap
    base2 = of_base + ROW_GAP + big_cap

    top = spread(bold, "AGE", BIG_PX, base1, PAD)
    bottom = spread(bold, "RMS", BIG_PX, base2, PAD)

    # Centre OF on the line: shift left by half its total advance width.
    of_adv = sum(glyph_path(semi, ch, OF_PX, 0, 0)[1] for ch in "OF")
    shift = of_adv / 2
    of_paths = []
    x = PAD + WIDTH / 2 - shift
    for ch in "OF":
        d, adv = glyph_path(semi, ch, OF_PX, x, of_base)
        of_paths.append(d)
        x += adv
    of_left, of_right = PAD + WIDTH / 2 - shift, PAD + WIDTH / 2 + shift

    ink_top, ink_bottom = top, bottom
    rule_y = of_top + of_cap / 2 - RULE_THICK / 2
    rules = [
        (PAD, rule_y, of_left - RULE_GAP - PAD),
        (of_right + RULE_GAP, rule_y, PAD + WIDTH - of_right - RULE_GAP),
    ]
    total_w = WIDTH + 2 * PAD
    total_h = base2 + PAD
    return {
        "w": round(total_w, 2),
        "h": round(total_h, 2),
        "big": ink_top + ink_bottom,
        "of": of_paths,
        "rules": rules,
    }


def svg(model, ink, gold):
    rule_rects = "".join(
        f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{RULE_THICK}" fill="{gold}"/>'
        for x, y, w in (tuple(round(v, 2) for v in r) for r in model["rules"])
    )
    big = f'<path fill="{ink}" d="{" ".join(model["big"])}"/>'
    of = f'<path fill="{gold}" d="{" ".join(model["of"])}"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {model["w"]:g} {model["h"]:g}" '
        f'role="img" aria-label="Age of RMS">{big}{rule_rects}{of}</svg>\n'
    )


def main():
    model = build()
    out = ROOT / "public" / "logo"
    out.mkdir(parents=True, exist_ok=True)
    for name, c in COLOURS.items():
        (out / f"age-of-rms-logo-{name}.svg").write_text(
            svg(model, c["ink"], c["gold"]), encoding="utf-8", newline="\n"
        )

    rules = ", ".join(
        f"{{ x: {x:g}, y: {y:g}, width: {w:g} }}"
        for x, y, w in (tuple(round(v, 2) for v in r) for r in model["rules"])
    )
    ts = (
        "// Generated by tools/logo/build_logo.py. Do not edit by hand.\n"
        "// Outlined Cinzel letters (SIL OFL 1.1), the geometry of the logo SVGs in\n"
        "// public/logo/.\n\n"
        f"export const LOGO_WIDTH = {model['w']:g};\n"
        f"export const LOGO_HEIGHT = {model['h']:g};\n"
        f"export const LOGO_RULE_THICKNESS = {RULE_THICK};\n"
        f'export const LOGO_BIG_PATH = "{" ".join(model["big"])}";\n'
        f'export const LOGO_OF_PATH = "{" ".join(model["of"])}";\n'
        f"export const LOGO_RULES = [{rules}];\n"
    )
    (ROOT / "src" / "components" / "logoPaths.ts").write_text(
        ts, encoding="utf-8", newline="\n"
    )
    print(model["w"], model["h"])


if __name__ == "__main__":
    main()
